#!/usr/bin/env python3
"""Reproducible renaming of the ALENEX connectivity chain (THEIRS) into
x-*.lisp books whose every defined symbol carries the prefix x-.

Usage: python3 rename.py
Reads  ../unassisted/{bitvec,...,connectivity}.lisp
Writes x-<book>.lisp here and renamed-symbols.txt (the rename table).

Rules:
  - a symbol is a maximal run of characters not in whitespace ( ) ' ` , " ;
  - comments (; to end of line, #| ... |#) and strings are left alone,
    except include-book strings naming one of the nine books
  - keywords (:foo) are never renamed
  - only symbols DEFINED in the nine books are renamed (defun defthm
    defthmd, and the names generated by defcong); matching is
    case-insensitive (ACL2 symbols are upcased by the reader)
  - *foo* -> *x-foo*, foo -> x-foo
"""
import os, re, sys

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "unassisted")
BOOKS = ["bitvec", "outer", "mmt", "scheme", "span", "add-dup",
         "add-arbitrary", "zero-subset", "connectivity"]
DEFINERS = {"defun", "defund", "defthm", "defthmd", "defconst", "defmacro",
            "define", "defun-nx", "deflabel", "deftheory", "defun-sk",
            "defchoose", "defequiv"}
DELIMS = set(" \t\n\r()'`,\";")
CONG = []  # (equiv1, equiv2, fn, k) of every defcong, filled by collect_defined

def tokenize(text):
    """Yield (kind, text) with kind in {'sym','str','comment','other'}."""
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == ';':
            j = text.find('\n', i)
            j = n if j < 0 else j
            yield ('comment', text[i:j]); i = j
        elif text.startswith('#|', i):
            j = text.find('|#', i)
            j = n if j < 0 else j + 2
            yield ('comment', text[i:j]); i = j
        elif c == '"':
            j = i + 1
            while j < n and text[j] != '"':
                if text[j] == '\\': j += 1
                j += 1
            yield ('str', text[i:j+1]); i = j + 1
        elif c in DELIMS:
            yield ('other', c); i += 1
        else:
            j = i
            while j < n and text[j] not in DELIMS: j += 1
            yield ('sym', text[i:j]); i = j

def collect_defined(tokens):
    names = set()
    toks = [t for t in tokens if t[0] != 'comment']
    for k in range(len(toks) - 3):
        if toks[k] == ('other', '(') and toks[k+1][0] == 'sym':
            head = toks[k+1][1].lower()
            if head in DEFINERS:
                # next symbol token (skip whitespace)
                m = k + 2
                while m < len(toks) and toks[m][0] == 'other' and toks[m][1].isspace():
                    m += 1
                if toks[m][0] == 'sym':
                    names.add(toks[m][1].lower())
            elif head == 'defcong':
                # (defcong equiv1 equiv2 (fn ...) k) -> equiv1-implies-equiv2-fn-k
                syms = []
                m = k + 2
                while m < len(toks) and len(syms) < 3:
                    if toks[m][0] == 'sym': syms.append(toks[m][1].lower())
                    m += 1
                # find k: the number after the closing paren of the term
                depth = 0; m2 = k + 2; seen_open = False
                while m2 < len(toks):
                    t = toks[m2]
                    if t == ('other', '('): depth += 1; seen_open = True
                    elif t == ('other', ')'):
                        depth -= 1
                        if seen_open and depth == 0:
                            m2 += 1; break
                    m2 += 1
                while m2 < len(toks) and not (toks[m2][0] == 'sym'):
                    m2 += 1
                kk = toks[m2][1]
                # generated name; only the function part is subject to renaming
                CONG.append((syms[0], syms[1], syms[2], kk))
    return names

def newname(s):
    if s.startswith('*') and s.endswith('*') and len(s) > 2:
        return '*x-' + s[1:]
    return 'x-' + s

def main():
    texts = {b: open(os.path.join(SRC, b + '.lisp')).read() for b in BOOKS}
    toklists = {b: list(tokenize(texts[b])) for b in BOOKS}
    defined = set()
    for b in BOOKS:
        defined |= collect_defined(toklists[b])
    # sanity: never rename these (library / ACL2 names that could appear)
    for bad in ["perm", "remove1-equal", "append", "len", "nth", "member-equal",
                "true-listp", "natp", "posp", "bitp", "zp", "nfix", "floor", "mod"]:
        assert bad not in defined, bad
    # defcong-generated names: old generated name -> new generated name
    special = {}
    for e1, e2, fn, kk in CONG:
        old = "%s-implies-%s-%s-%s" % (e1, e2, fn, kk)
        new = "%s-implies-%s-%s-%s" % (e1, e2, newname(fn) if fn in defined else fn, kk)
        if old != new: special[old] = new
    count = {}
    for b in BOOKS:
        out = []
        for kind, t in toklists[b]:
            if kind == 'sym' and not t.startswith(':') and t.lower() in defined:
                out.append(newname(t)); count[t.lower()] = count.get(t.lower(), 0) + 1
            elif kind == 'sym' and t.lower() in special:
                out.append(special[t.lower()]); count[t.lower()] = count.get(t.lower(), 0) + 1
            elif kind == 'str' and t[1:-1] in BOOKS:
                out.append('"x-' + t[1:-1] + '"')
            else:
                out.append(t)
        header = ("; x-%s.lisp -- MECHANICAL RENAMING (prefix x-) of ../unassisted/%s.lisp\n"
                  "; produced by rename.py in this directory; do not edit by hand.\n"
                  % (b, b))
        open('x-' + b + '.lisp', 'w').write(header + ''.join(out))
    with open('renamed-symbols.txt', 'w') as f:
        f.write("# %d symbols defined in the nine books, renamed old -> new (occurrences)\n" % len(defined))
        for s in sorted(defined):
            f.write("%s -> %s (%d)\n" % (s, newname(s), count.get(s, 0)))
        f.write("# defcong-generated names (renamed only through their function symbol)\n")
        for o, nw in sorted(special.items()):
            f.write("%s -> %s (%d)\n" % (o, nw, count.get(o, 0)))
    print("renamed", len(defined), "symbols;", sum(count.values()), "occurrences")

if __name__ == '__main__':
    main()
