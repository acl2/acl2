# Decodes the rank-245 scheme block from submission.tex (Appendix A) into
# an ACL2 constant.  Each term is written as a list of three natural
# numbers (A B C); bit 7*i+j of a number records coordinate [i,j].
import base64, zlib, sys
BEGIN = "BEGIN-RANK245-7X7X7-ZLIB-BASE32"
END = "END-RANK245-7X7X7-ZLIB-BASE32"
N = 7
RANK = 245
text = open(sys.argv[1]).read()
payload = text.split(BEGIN, 1)[1].split(END, 1)[0]
payload = "".join(payload.split())
payload += "=" * (-len(payload) % 8)
data = zlib.decompress(base64.b32decode(payload))
assert len(data) == RANK * 3 * N
terms = []
for o in range(0, len(data), 21):
    masks = [int.from_bytes(data[o + p : o + p + 7], "little") for p in (0, 7, 14)]
    assert not any(m >> (N * N) for m in masks)
    assert all(m for m in masks)
    terms.append(masks)
assert len(set(tuple(t) for t in terms)) == RANK
# independent sanity check (same as the paper's Python verifier)
parity = set()
for A, B, C in terms:
    for a in range(N*N):
        if not A >> a & 1: continue
        for b in range(N*N):
            if not B >> b & 1: continue
            for c in range(N*N):
                if not C >> c & 1: continue
                key = (a, b, c)
                if key in parity: parity.remove(key)
                else: parity.add(key)
expected = {(i*N+j, j*N+k, i*N+k) for i in range(N) for j in range(N) for k in range(N)}
assert parity == expected, "python check failed"
with open(sys.argv[2], "w") as f:
    f.write("; Generated by decode_scheme.py from Appendix A of submission.tex.\n")
    f.write("; Each entry is (A B C): three 49-bit masks, bit 7*i+j = entry [i,j].\n")
    f.write("(in-package \"ACL2\")\n\n(defconst *rank245-masks*\n  '(\n")
    for A, B, C in terms:
        f.write(f"    ({A} {B} {C})\n")
    f.write("    ))\n")
print("decoded", len(terms), "terms; python parity check passed")
